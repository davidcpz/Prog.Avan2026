let frutas = ["manzana", "banana", "pera"];

console.log("Array original:");
console.log(frutas);

// Agregamos una fruta al final
frutas.push("naranja");

console.log("Después de usar push:");
console.log(frutas);

// Eliminamos la última fruta
frutas.pop();

console.log("Después de usar pop:");
console.log(frutas);